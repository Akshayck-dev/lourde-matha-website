import { chromium } from 'playwright-core';
const EXE = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1243/chrome-headless-shell-linux64/chrome-headless-shell';
const b = await chromium.launch({ executablePath: EXE });
const errs = [];
const d = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
d.on('pageerror', e => errs.push(e.message));
await d.goto('http://localhost:4173/about', { waitUntil: 'networkidle' });
await d.waitForTimeout(800);
await d.evaluate(() => [...document.querySelectorAll('h2')].find(h => h.textContent.includes('Sacraments')).scrollIntoView({ block: 'start' }));
await d.waitForTimeout(1600);
await d.screenshot({ path: '/tmp/sec-sacraments.png' });
await d.evaluate(() => [...document.querySelectorAll('h2')].find(h => h.textContent.includes('Ministries')).scrollIntoView({ block: 'start' }));
await d.waitForTimeout(1600);
await d.screenshot({ path: '/tmp/sec-ministries.png' });
await d.goto('http://localhost:4173/events', { waitUntil: 'networkidle' });
await d.waitForTimeout(800);
await d.evaluate(() => [...document.querySelectorAll('h2')].find(h => h.textContent.includes('Our Feasts')).scrollIntoView({ block: 'start' }));
await d.waitForTimeout(1600);
await d.screenshot({ path: '/tmp/sec-feasts.png' });
// anchor link check
await d.click('text=Watch the 2026 feast');
await d.waitForTimeout(1200);
const atVideos = await d.evaluate(() => {
  const el = document.getElementById('feast-videos');
  const r = el.getBoundingClientRect();
  return r.top < window.innerHeight && r.bottom > 0;
});
console.log('anchor lands on videos:', atVideos);
const m = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
m.on('pageerror', e => errs.push('mobile: ' + e.message));
await m.goto('http://localhost:4173/about', { waitUntil: 'networkidle' });
await m.waitForTimeout(800);
await m.evaluate(() => [...document.querySelectorAll('h2')].find(h => h.textContent.includes('Sacraments')).scrollIntoView({ block: 'start' }));
await m.waitForTimeout(1600);
await m.screenshot({ path: '/tmp/sec-sacraments-m.png' });
const overflow = await m.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
console.log('mobile h-overflow:', overflow);
console.log('ERRORS:', JSON.stringify(errs));
await b.close();
